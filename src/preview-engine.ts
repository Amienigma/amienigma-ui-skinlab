/**
 * PreviewEngine for SkinLab
 * Handles live preview of skins across device frames,
 * theme switching, export to CSS/JSON, and comparison modes.
 * 
 * @module PreviewEngine
 * @version 1.0.0
 * @date 2026-11-19
 */

export interface SkinPreview {
  id: string;
  name: string;
  cssVariables: Record<string, string>;
  components: string[];
}

export class PreviewEngine {
  private previews: Map<string, SkinPreview> = new Map();
  private activeId: string | null = null;
  private deviceFrame: 'phone' | 'tablet' | 'fold' = 'phone';

  addPreview(preview: SkinPreview): void {
    this.previews.set(preview.id, preview);
    if (!this.activeId) this.activeId = preview.id;
  }

  setActive(id: string): void {
    if (this.previews.has(id)) this.activeId = id;
  }

  getActive(): SkinPreview | null {
    return this.activeId ? this.previews.get(this.activeId) || null : null;
  }

  setDeviceFrame(frame: 'phone' | 'tablet' | 'fold'): void {
    this.deviceFrame = frame;
  }

  generateCSS(): string {
    const active = this.getActive();
    if (!active) return '';
    const vars = Object.entries(active.cssVariables)
      .map(([k, v]) => `  --${k}: ${v};`)
      .join('\n');
    return `:root {
${vars}
}

/* Generated by SkinLab PreviewEngine */`;
  }

  exportJSON(): string {
    return JSON.stringify({
      active: this.activeId,
      device: this.deviceFrame,
      previews: Array.from(this.previews.values()),
    }, null, 2);
  }

  compare(ids: string[]): { differences: string[] } {
    const skins = ids.map(id => this.previews.get(id)).filter(Boolean) as SkinPreview[];
    const differences: string[] = [];
    if (skins.length < 2) return { differences };
    const keys = new Set(skins.flatMap(s => Object.keys(s.cssVariables)));
    for (const key of keys) {
      const values = skins.map(s => s.cssVariables[key]);
      if (new Set(values).size > 1) {
        differences.push(`${key}: ${values.join(' vs ')}`);
      }
    }
    return { differences };
  }

  list(): SkinPreview[] {
    return Array.from(this.previews.values());
  }
}

export default PreviewEngine;
